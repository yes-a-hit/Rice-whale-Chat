def patch(path, pairs, tail):
    p = root / path
    t = io.open(p, encoding="utf-8").read()
    assert tail in t, path
    block = "".join(f"  {k}: '{v}',\n" for k, v in pairs)
    t = t.replace(tail, "\n" + block + tail.lstrip("\n"), 1)
    io.open(p, "w", encoding="utf-8", newline="\n").write(t)
    print("patched", path, len(pairs), "keys")


